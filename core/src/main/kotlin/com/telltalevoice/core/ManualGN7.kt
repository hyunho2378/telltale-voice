    fun meaning(no: Int): String = section(no).lines[MEANING_INDEX[no] ?: 0]

    /**
     * 조치 방법 문장: 경고등 쪽에서 "~십시오"가 든 문장("~참고하십시오."로 끝나는 안내 문장은 뺌)과, 위 다른 쪽 원문.
     * 경고등 정보와 정차 후 화면이 같은 함수를 쓴다.
     */
    fun actions(no: Int): List<String> =
        (ACTIONS_BEFORE[no] ?: emptyList()) +
            section(no).lines.filter { it.contains("십시오") && !it.endsWith("참고하십시오.") } +
            (ACTIONS_AFTER[no] ?: emptyList())

